#!/usr/bin/env node
/**
 * Rasterize refined Aspera Hub brand SVGs into PNGs used by the app, packager, and website.
 * Run: node scripts/render-brand-icons.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brandDir = join(root, 'src', 'assets', 'brand');
const assetsDir = join(root, 'assets');
const websiteAssets = join(root, 'website', 'assets');

mkdirSync(brandDir, { recursive: true });
mkdirSync(assetsDir, { recursive: true });
mkdirSync(websiteAssets, { recursive: true });

const iconSvg = readFileSync(join(brandDir, 'icon.svg'), 'utf8');
const markSvg = readFileSync(join(brandDir, 'aspera-a.svg'), 'utf8');

function renderPng(svg, size) {
  const resvg = new Resvg(svg, {
    fitTo: { mode: 'width', value: size },
    background: 'rgba(0,0,0,0)',
  });
  return resvg.render().asPng();
}

const sizes = [16, 24, 32, 48, 64, 128, 256, 512];
for (const size of sizes) {
  const buf = renderPng(iconSvg, size);
  writeFileSync(join(brandDir, `icon-${size}.png`), buf);
  writeFileSync(join(assetsDir, `icon-${size}.png`), buf);
  console.log(`wrote icon-${size}.png`);
}

const icon512 = renderPng(iconSvg, 512);
writeFileSync(join(brandDir, 'icon.png'), icon512);
writeFileSync(join(assetsDir, 'icon.png'), icon512);
writeFileSync(join(websiteAssets, 'icon.png'), icon512);
console.log('wrote icon.png (512)');

const fav64 = renderPng(iconSvg, 64);
writeFileSync(join(websiteAssets, 'favicon-64.png'), fav64);
writeFileSync(join(root, 'website', 'favicon-64.png'), fav64);

const mark256 = renderPng(markSvg, 256);
writeFileSync(join(brandDir, 'aspera-a.png'), mark256);

const icon256 = renderPng(iconSvg, 256);
const b64 = icon256.toString('base64');
writeFileSync(
  join(root, 'src', 'appIconData.js'),
  `/** Generated by scripts/render-brand-icons.mjs — do not edit by hand. */\n` +
    `export const APP_ICON_PNG_DATA_URL = 'data:image/png;base64,${b64}';\n`
);
console.log('wrote src/appIconData.js');

console.log('Brand icons rendered.');
